/** 이 거리(km)보다 멀면 "구"를 알 수 없다고 보고 가까운 시·지역 이름을 보여요 */
export const DISTRICT_MAX_KM = 12;

export type Located = { /** 화면에 보일 이름(예: "부산 해운대구") */ label: string; /** 편지가 출발할 지역(core/places.ts) */ place: Place };

export function locate(lat: number, lng: number): Located {
  const place = nearestPlace(lat, lng);
  // 서울은 places.ts의 25개 구를, 광역시는 위 구 목록을 함께 견줘요
  const seoul = PLACES.filter((p) => p.region === "서울").map((p) => D(p.name, p.lat, p.lng));
  let best: District | null = null, bestKm = Infinity;
  for (const d of [...seoul, ...DISTRICTS]) {
    const km = haversineKm(lat, lng, d.lat, d.lng);
    if (km < bestKm) { best = d; bestKm = km; }
  }
  return { label: best && bestKm <= DISTRICT_MAX_KM ? best.name : place.name, place };
}
